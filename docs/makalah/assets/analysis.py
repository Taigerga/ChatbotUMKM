import pandas as pd, numpy as np
raw = 'data/raw/'
df = pd.read_csv(raw + 'ecommerce_sales_customer_analytics_150k.csv', encoding='utf-8', encoding_errors='replace', low_memory=False)
items = pd.read_csv(raw + 'order_items.csv', encoding='utf-8', encoding_errors='replace', low_memory=False)
cat = pd.read_csv(raw + 'product_catalog.csv', encoding='utf-8', encoding_errors='replace')
print('shape', df.shape, items.shape, cat.shape)
print('order_date min/max', df.order_date.min(), df.order_date.max())
print('null rating by status'); print(df.groupby('order_status')['customer_rating'].apply(lambda s: (s.isna().mean() * 100).round(1)))
print('non-null rating', df.customer_rating.notna().sum(), 'null', df.customer_rating.isna().sum())
print('net_sales sum', round(df.net_sales.sum(), 2))
print('gross sum', round(df.gross_sales.sum(), 2))
print('profit sum', round(df.profit.sum(), 2))
print('AOV', round(df.net_sales.sum() / len(df), 2))
print('return rate', round(9462 / len(df) * 100, 2), 'cancel', round(8398 / len(df) * 100, 2))
print('items/order', round(len(items) / df.order_id.nunique(), 2))
print('items dup full', items.duplicated().sum(), 'items dup order+product', items.duplicated(subset=['order_id', 'product_id']).sum())
print(items.groupby('order_id').size().describe())
print('unique products in items', items.product_id.nunique())
m = items.merge(df[['order_id', 'customer_id']], on='order_id', how='left')
pairs = m[['customer_id', 'product_id']].drop_duplicates()
print('pairs', pairs.shape[0], 'sparsity %', round((1 - pairs.shape[0] / (df.customer_id.nunique() * items.product_id.nunique())) * 100, 2))
per_cust = m.groupby('customer_id').product_id.nunique()
print('cust 1 product', (per_cust == 1).sum(), round((per_cust == 1).mean() * 100, 1), '>=5', (per_cust >= 5).sum())
df['d'] = pd.to_datetime(df.order_date)
ref = pd.Timestamp('2025-12-31')
last = df.groupby('customer_id').d.max()
print('customers', len(last), 'churn365', (last < ref - pd.Timedelta(days=365)).sum(), 'active365', (last >= ref - pd.Timedelta(days=365)).sum())
single = df.groupby('customer_id').size()
print('single-transaction customers', (single == 1).sum())
print('freq mean', round(single.mean(), 2), 'median', single.median())
print(df.review_sentiment.value_counts(dropna=False))
print(df.gender.value_counts())
print(df.customer_country.value_counts())
print(df.region.value_counts())
print(df.order_status.value_counts())
print(cat.product_category.value_counts())
print('U+FFFD count', int(df.astype(str).apply(lambda s: s.str.contains('\ufffd').sum()).sum()))
print('review words median', df.customer_review.fillna('').str.split().str.len().median())
print('avg rating', round(df.customer_rating.mean(), 3))
print('revenue check (net)', round(df.net_sales.sum(), 2), 'vs 177134263.74')
print('total profit', round(df.profit.sum(), 2))
print('campaign_name non-null', df.campaign_name.notna().sum(), 'coupon non-null', df.coupon_code.notna().sum())
print('delivery_days non-null', df.delivery_days.notna().sum())
print('rating non-null', df.customer_rating.notna().sum())
print('is_repeat_customer', df.is_repeat_customer.value_counts().to_dict())
print('customer_order_count describe', df.customer_order_count.describe().round(2).to_dict())
print('segment counts', df.customer_segment.value_counts().to_dict())
print('type counts', df.customer_type.value_counts().to_dict())
print('region counts', df.region.value_counts().to_dict())
print('top states', df.customer_state.value_counts().head(5).to_dict())
print('n countries', df.customer_country.nunique(), 'n states', df.customer_state.nunique(), 'n cities', df.customer_city.nunique())
print('returns returned orders', (df.return_status == 'Returned').sum())
print('order_status pct', (df.order_status.value_counts(normalize=True) * 100).round(2).to_dict())
print('sentiment pct of nonblank', (df.review_sentiment.value_counts(normalize=True) * 100).round(2).to_dict())
